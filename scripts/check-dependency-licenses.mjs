#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "THIRD_PARTY_NOTICES.md");
const mode = process.argv[2] ?? "--check";

const ALLOWED_LICENSES = new Set([
  "(Apache-2.0 AND BSD-3-Clause)",
  "0BSD",
  "Apache-2.0",
  "BlueOak-1.0.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "CC-BY-4.0",
  "ISC",
  "MIT",
  "MPL-2.0",
  "OFL-1.1",
  "Unlicense",
]);

const REVIEWED_MISSING_METADATA = new Map([
  ["buffers@0.1.1", "published metadata omits the license; the upstream/Debian record confirms MIT"],
  ["buildcheck@0.0.7", "published metadata uses the legacy licenses field and links the upstream MIT license"],
  ["cpu-features@0.0.10", "published metadata uses the legacy licenses field and links the upstream MIT license"],
]);

function normalizeLicense(value) {
  if (typeof value === "string") {
    const normalized = value.trim();
    if (normalized === "MIT/X11") return "MIT";
    return normalized;
  }
  if (Array.isArray(value)) {
    const types = [...new Set(value.map((item) => normalizeLicense(item?.type ?? item)).filter(Boolean))];
    if (types.length === 1) return types[0];
    if (types.length > 1) return `(${types.sort().join(" OR ")})`;
  }
  if (value && typeof value === "object" && "type" in value) {
    return normalizeLicense(value.type);
  }
  return "";
}

function markdown(value) {
  return String(value).replaceAll("|", "\\|");
}

function classification(name, version, license, reviewedException) {
  if (name === "@layerzerolabs/lz-evm-protocol-v2" && version === "3.0.168") {
    if (license !== "LZBL-1.2") throw new Error("The reviewed LayerZero license changed");
    return "source-available; reviewed exact transitive exception";
  }
  if (license === "LZBL-1.2") {
    throw new Error(`Unreviewed source-available dependency: ${name}@${version}`);
  }
  if (!ALLOWED_LICENSES.has(license)) {
    throw new Error(`Unreviewed dependency license ${license || "<missing>"}: ${name}@${version}`);
  }
  if (reviewedException) return "permissive; reviewed metadata exception";
  if (license === "MPL-2.0") return "weak copyleft dependency";
  if (license === "CC-BY-4.0" || license === "OFL-1.1") return "asset or data license";
  return "permissive";
}

async function dependencyInventory() {
  const lock = JSON.parse(await readFile(resolve(ROOT, "package-lock.json"), "utf8"));
  const inventory = new Map();

  for (const [relativePath, lockEntry] of Object.entries(lock.packages ?? {})) {
    if (!relativePath.includes("node_modules/")) continue;
    const packageJsonPath = resolve(ROOT, relativePath, "package.json");
    const packageJson = existsSync(packageJsonPath)
      ? JSON.parse(await readFile(packageJsonPath, "utf8"))
      : {};
    const name = packageJson.name ?? relativePath.split("node_modules/").at(-1);
    const version = packageJson.version ?? lockEntry.version;
    if (typeof name !== "string" || name.startsWith("@proofline/")) continue;
    if (typeof version !== "string") throw new Error(`Dependency version is missing: ${name}`);

    let license = normalizeLicense(packageJson.license ?? packageJson.licenses ?? lockEntry.license);
    let reviewedException = "";
    const missingMetadataReview = REVIEWED_MISSING_METADATA.get(`${name}@${version}`);
    if (!license && missingMetadataReview) {
      license = "MIT";
      reviewedException = missingMetadataReview;
    }
    if (!license) throw new Error(`Dependency license is missing: ${name}@${version}`);

    const row = {
      name,
      version,
      license,
      classification: classification(name, version, license, reviewedException),
      reviewedException,
    };
    const key = `${name}@${version}`;
    const prior = inventory.get(key);
    if (prior && prior.license !== row.license) {
      throw new Error(`Conflicting dependency licenses for ${key}`);
    }
    inventory.set(key, row);
  }

  return [...inventory.values()].sort((left, right) =>
    left.name.localeCompare(right.name) || left.version.localeCompare(right.version));
}

function render(rows) {
  const table = rows.map((row) =>
    `| ${markdown(row.name)} | ${markdown(row.version)} | ${markdown(row.license)} | ${markdown(row.classification)} |`).join("\n");
  return `# Third-party dependency licenses

This file is generated by \`scripts/check-dependency-licenses.mjs\` from the
exact installed dependency graph. Do not edit it manually. Run \`npm ci\` and
\`npm run check:licenses\` to verify it.

Orivra's Apache-2.0 license does not replace any dependency license. This
inventory is provided for transparency and is not legal advice.

## Reviewed exceptions

- \`buffers@0.1.1\` omits a license field from its published package metadata.
  The upstream/Debian copyright record identifies it as MIT; only this exact
  package and version receive the metadata exception.
- \`buildcheck@0.0.7\` and \`cpu-features@0.0.10\` use the legacy npm
  \`licenses\` metadata field and link their upstream MIT license. Only these
  exact package versions receive the metadata exception.
- \`@layerzerolabs/lz-evm-protocol-v2@3.0.168\` is an exact transitive
  dependency of the Flare contract-artifact package and is licensed under
  LZBL-1.2. It is source-available, not represented as open source, and any
  version or license change fails this check pending review.

## Inventory (${rows.length} unique package versions)

| Package | Version | License | Classification |
| --- | --- | --- | --- |
${table}
`;
}

const rendered = render(await dependencyInventory());
if (mode === "--write") {
  await writeFile(OUTPUT, rendered, "utf8");
  process.stdout.write(`Wrote ${OUTPUT}\n`);
} else if (mode === "--check") {
  if (!existsSync(OUTPUT)) throw new Error("THIRD_PARTY_NOTICES.md is missing; run the script with --write");
  const current = await readFile(OUTPUT, "utf8");
  if (current !== rendered) {
    throw new Error("THIRD_PARTY_NOTICES.md is stale; run the script with --write");
  }
  process.stdout.write("Dependency license inventory is current.\n");
} else {
  throw new Error("Usage: check-dependency-licenses.mjs [--check|--write]");
}
